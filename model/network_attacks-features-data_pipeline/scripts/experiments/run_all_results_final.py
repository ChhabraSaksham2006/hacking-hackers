"""Run the complete baseline + Sparse RSSM benchmark into ``results_final``.

Runs one horizon per subprocess to bound memory, resumes completed runs, and
uses tqdm when available (with a dependency-free fallback). All metrics are
generated by the existing model/evaluation implementations.
"""
from __future__ import annotations
import argparse, json, shutil, subprocess, sys, time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HORIZONS = [1, 3, 5, 10, 25, 50, 100, 200]
SPARSITIES = [("top05", .05), ("top10", .10), ("top25", .25), ("top50", .50), ("dense", 1.0)]

try:
    from tqdm import tqdm
except ImportError:
    def tqdm(items, **kwargs):
        return items

def run(cmd, log: Path):
    log.parent.mkdir(parents=True, exist_ok=True)
    with log.open("a", encoding="utf-8") as fh:
        fh.write(f"\n\n$ {' '.join(map(str, cmd))}\n")
        p = subprocess.run(cmd, cwd=ROOT, stdout=fh, stderr=subprocess.STDOUT)
    if p.returncode:
        raise RuntimeError(f"Command failed ({p.returncode}); see {log}")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", type=Path, default=ROOT / "results_final")
    ap.add_argument("--epochs", type=int, default=5)
    ap.add_argument("--batch-size", type=int, default=256)
    ap.add_argument("--resume", action="store_true", default=True)
    args = ap.parse_args()
    out = args.results_dir if args.results_dir.is_absolute() else ROOT / args.results_dir
    out.mkdir(parents=True, exist_ok=True)
    baseline_dir = out / "baselines"
    baseline_dir.mkdir(exist_ok=True)
    log = out / "orchestrator.log"
    manifest = {"horizons": HORIZONS, "sparsities": [x[1] for x in SPARSITIES], "state_dim": 54, "started": time.time()}
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    baseline_tasks = [("baseline", k, None) for k in HORIZONS]
    rssm_tasks = [(name, k, ratio) for name, ratio in SPARSITIES for k in HORIZONS]
    attn_tasks = [("top10_attn", k, .10) for k in HORIZONS]
    tasks = baseline_tasks + rssm_tasks + attn_tasks
    for i, (kind, k, ratio) in enumerate(tqdm(tasks, desc="expanded benchmark", unit="run"), 1):
        if kind == "baseline":
            marker = baseline_dir / f"06_multihorizon_comparison_k{k}.csv"
            if args.resume and marker.exists():
                continue
            run([sys.executable, "scripts/experiments/run_baseline_suite.py", "--horizon", str(k), "--epochs", str(args.epochs)], out / "logs" / f"baseline_k{k}.log")
            src = ROOT / "reports/baselines/06_multihorizon_comparison.csv"
            shutil.copy2(src, marker)
            for p in (ROOT / "reports/baselines").glob("*.csv"):
                if p.name != "06_multihorizon_comparison.csv":
                    shutil.copy2(p, baseline_dir / p.name)
        else:
            tag = f"{kind}/k{k}"
            marker = out / "sparse_rssm" / tag / "test_metrics.json"
            if args.resume and marker.exists():
                continue
            cmd = [sys.executable, "scripts/experiments/run_sparse_rssm.py", "--sparsity", str(ratio), "--horizon", str(k), "--epochs", str(args.epochs), "--batch-size", str(args.batch_size), "--results-dir", str(out / "sparse_rssm")]
            if kind == "top10_attn": cmd.append("--use-attention")
            run(cmd, out / "logs" / f"{kind}_k{k}.log")
    run([sys.executable, "scripts/experiments/compare_sparse_rssm.py", "--rssm-dir", str(out / "sparse_rssm"), "--baseline-dir", str(baseline_dir), "--out-dir", str(out / "comparison")], log)
    manifest["finished"] = time.time()
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"Completed. Results: {out}")

if __name__ == "__main__": main()
